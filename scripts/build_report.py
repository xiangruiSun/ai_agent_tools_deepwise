"""Build verification/REPORT.md from the JSON evidence files. Every number in the report is read
from those files; nothing is typed in by hand.

    python scripts/build_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

V = Path(__file__).resolve().parents[1] / "verification"


def load(name: str) -> dict | None:
    p = V / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    L: list[str] = ["# Verification report", "",
                    "Generated by `scripts/build_report.py` from the JSON files in this folder. Each task was run by "
                    "`scripts/verify.py` on the real data with the local model. Counts are over 10 CT studies unless "
                    "stated. Small samples: read these as what happened on this data, not as general performance.", ""]

    def head(task: str, title: str, d: dict | None) -> bool:
        L.extend([f"## {task} {title}", ""])
        if d is None:
            L.extend(["Not run yet.", ""])
            return False
        L.extend([f"Ran {d['ran_at']} with `{d['model']}`. Evidence: `{d['task']}.json`.", ""])
        return True

    d = load("t01_tool_calling_agent")
    if head("T01", "Tool-calling agent", d):
        s = d["summary"]
        b = load("t01_before_guards")
        rows = [["Runs completed", f"{s['completed']}/{s['of']}"],
                ["Exam category correct", f"{s['exam_category_correct']}/{s['of']}"],
                ["Tool errors across the runs", s.get("tool_errors", "n/a")],
                ["Answers sent back by the grounding guard", f"{s.get('answers_sent_back_by_guard', 'n/a')}/{s['of']}"],
                ["Median model calls / tool calls / tokens / seconds",
                 f"{s['median_iterations']} / {s['median_tool_calls']} / {s['median_tokens']} / {s['median_wall_s']}"]]
        L.extend([table(["Atomic tools only, one question per study", "Result"], rows), ""])
        if b:
            bs = b["summary"]
            berr = sum(r["tool_errors"] for r in b["studies"])
            L.extend([f"First run, before the grounding guard and the clearer `is_new` / `is_growing` descriptions "
                      f"(`t01_before_guards.json`): {berr} tool errors across the 10 runs, median {bs['median_tokens']} "
                      f"tokens. Its correctness count ({bs['exam_category_correct']}/10) used a looser text match and is "
                      "not directly comparable.", ""])
        f = d["fault_injection"]
        L.extend([table(["Fault injected", "What happened"], [
            ["Retrieval service down", f"retried: {f['service_down']['retried']}; reported the failure and still answered: {f['service_down']['reported_failure_and_continued']}"],
            ["Arguments the tool rejects", f"run {f['invalid_arguments']['status']}; final answer correct: {f['invalid_arguments']['correct']}"],
            ["Tool slower than its timeout", f"timeout observed: {f['timeout']['timeout_seen']}; run {f['timeout']['status']}"],
            ["Step limit of 3", f"stopped: {f['max_iterations']['stop_reason']} after {f['max_iterations']['iterations']} model calls, with a wrap-up answer"]]), ""])

    d = load("t02_structured_output")
    if head("T02", "Structured output and validation", d):
        s = d["summary"]
        rows = [[m.replace("_", " "), f"{s[m]['first_pass']}/{s[m]['of']}", f"{s[m]['valid']}/{s[m]['of']}", s[m]["mean_attempts"]]
                for m in ("schema_constrained", "free_text_json")]
        L.extend([table(["Mode (8 studies with findings)", "Valid on first attempt", "Valid within 3 attempts", "Mean attempts"], rows), "",
                  f"Negative control (one wrong category planted in the facts): caught by the business rules in "
                  f"{s['wrong_category_caught']}/{s['of']} studies.", "",
                  table(["Authorization check", "Outcome"], [[k.replace("_", " "), v] for k, v in d["authorization_matrix"].items()]), ""])

    d = load("t03_agent_runtime")
    if head("T03", "Agent runtime", d):
        s, c = d["summary"], d["crash_and_resume"]
        L.extend([table(["Pipeline on 10 studies", "Result"], [
            ["Signed after approval and resume", f"{s['signed']}/{s['of']}"],
            ["Exam category equals code-computed truth", f"{s['exam_category_correct']}/{s['of']}"],
            ["Drafts: model / template (no findings) / template fallback", f"{s['model_drafts']} / {s['template_drafts']} / {s['template_fallbacks']}"],
            ["Critical results flagged", s["critical_flagged"]],
            ["Median seconds / tokens per study", f"{s['median_wall_s']} / {s['median_tokens']}"]]), "",
            f"Crash during `{c['crashed_at']}`: run status `{c['crashed_status']}`; resumed by a fresh environment to "
            f"`{c['resumed_waiting_for']}`; detector runs in that run: {c['detector_runs_total']}. "
            f"Human rejection: outcome `{d['human_rejection']['outcome']}`. Step limit: `{d['step_limit']['detail']}`, "
            f"stopped before `{d['step_limit']['stopped_before']}`.", ""])

    d = load("t04_reasoning_and_planning")
    if head("T04", "Reasoning strategies and planning", d):
        rows = [[k.replace("_", " "), f"{v['correct']}/{v['of']}", v["mean_calls"], v["mean_tokens"], v["mean_latency_ms"]]
                for k, v in d["strategies"].items()]
        L.extend([f"{d['n_items']} real reader-confirmed nodules, each asked as one Lung-RADS question.", "",
                  table(["Strategy", "Correct", "Mean model calls", "Mean tokens", "Mean ms"], rows), "",
                  table(["Planner / executor goal", "Status", "Parallel levels", "Steps ok", "Plan attempts", "Tokens", "Seconds"],
                        [[p["goal"][:70] + "…", p["status"], " → ".join("[" + ", ".join(lv) + "]" for lv in p["levels"]),
                          f"{sum(p['step_ok'].values())}/{len(p['step_ok'])}", p["plan_attempts"], p["tokens"], p["wall_s"]]
                         for p in d["planner_executor"]]), ""])

    d = load("t05_tools_vs_skills")
    if head("T05", "Tools versus skills", d):
        a, k = d["atomic_tools"]["summary"], d["skill"]["summary"]
        rows = [[lab, a[key], k[key]] for lab, key in [
            ("Exam category correct (of 10)", "exam_correct"), ("All findings reported with size (of 10)", "all_findings_reported"),
            ("Quality gate actually run (of 10)", "quality_gate_run"), ("Mean model calls", "mean_llm_calls"),
            ("Mean tool calls made by the model", "mean_model_tool_calls"), ("Mean tokens", "mean_tokens"),
            ("Mean seconds", "mean_wall_s"), ("Tool errors", "tool_errors")]]
        rows.append(["Tool schema size in the prompt (tokens, estimate)", d["tool_schema_tokens_estimate"]["atomic_tools"],
                     d["tool_schema_tokens_estimate"]["skill"]])
        L.extend([table(["Same question, 10 studies", "4 atomic tools", "1 skill"], rows), ""])

    d = load("t06_memory")
    if head("T06", "Memory", d):
        lt, st, w = d["long_term"], d["short_term"], d["working_context"]
        L.extend([table(["Check", "Result"], [
            ["`remember` tool called when asked", lt["remember_tool_called"]], ["Stored", "; ".join(lt["stored"]) or "nothing"],
            ["Recalled in a new session", bool(lt["new_session_recalled"])], ["Requested style applied in the new session", lt["style_applied"]],
            ["Another user recalled nothing", lt["other_user_isolated"]],
            ["Follow-up resolved from session history", st["follow_up_resolved_from_history"]],
            ["Long run: history size → size sent (token estimate, budget 2,500)", f"{w['history_tokens_estimate']} → {w['sent_tokens_estimate']} over {w['tool_calls']} tool calls"],
            ["Long run status", f"{w['status']} after {w['iterations']} model calls"]]), ""])

    d = load("t07_mcp")
    if head("T07", "Model Context Protocol", d):
        tools = ", ".join(t["name"] for t in d["discovered_tools"])
        am = d["agent_over_mcp"]
        keys = list(next(iter(d["server_side_authorization_matrix"].values())))
        L.extend([f"Server `{d['server']['name']}`, protocol {d['server']['protocol_version']}, {d['transport']}; connect and "
                  f"first call {d['connect_and_first_call_s']} s. Discovered: {tools}.", "",
                  f"Agent loop over MCP tools only: `{am['status']}`, {len(am['tool_log'])} tool calls, {am['tokens']} tokens, "
                  f"category correct: {am['category_correct']}. `get_report` hidden by the host allowlist: {d['get_report_hidden_by_host']}.", "",
                  table(["Token", *keys], [[k, *[v[x] for x in keys]] for k, v in d["server_side_authorization_matrix"].items()]), ""])

    d = load("t08_multi_agent")
    if head("T08", "Multi-agent", d):
        rows = []
        for p in ("single", "sequential", "hierarchical", "network"):
            if p in d:
                s = d[p]["summary"]
                rows.append([p, s["n"], s["mean_score_of_6"], s["perfect"], s["failure_rate"], s["mean_tokens"], s["mean_llm_calls"], s["mean_wall_s"]])
        b = d["blackboard_concurrency"]
        L.extend([table(["Pattern", "Studies", "Mean score (of 6)", "Perfect", "Failure rate", "Mean tokens", "Mean model calls", "Mean seconds"], rows), "",
                  f"Blackboard: {b['writers']} writers × {b['appends_each']} appends, {b['items_stored']} stored, "
                  f"{b['conflicts_detected_and_retried']} conflicts detected and retried, {b['lost_updates']} lost updates.", ""])

    d = load("t09_ct_diagnosis")
    if head("T09", "CT diagnosis layer", d):
        s = d["detector_summary"]
        L.extend([f"Detector `{d['detector']}` against the LIDC readers: {s['detected']}/{s['reader_nodules']} nodules found "
                  f"(sensitivity {s['sensitivity']}), {s['false_positives_per_scan']} false positives per scan, median "
                  f"{s['median_runtime_s']} s per study. Lung-RADS boundary table ({len(d['lung_rads_boundary_table'])} cases) "
                  f"all correct: {d['lung_rads_table_all_correct']}.", "",
                  table(["Study", "Reader nodules", "Detected", "Missed (mm, type)", "False positives", "Exam category"],
                        [[r["patient_id"], r["reader_nodules"], r["detected"],
                          ", ".join(f"{m['mm']} {m['type']}" for m in r["missed"]) or "none", r["false_positives"], r["exam_lung_rads"]]
                         for r in d["studies"]]), ""])

    d = load("t10_training_data")
    if head("T10", "Training data governance", d):
        de, co, la = d["deid_audit"], d["cohort_builder"], d["label_extraction"]
        L.extend([f"De-identification audit: {de['passed']}/{de['studies']} studies passed; findings: {de['findings'] or 'none'}.", "",
                  table(["Cohort request", "Query matches hand-written", "Scans (model query)", "Scans (hand-written)"],
                        [[c["request"], c["query_matches_expected"], c.get("matching_scans", "n/a"), c["expected_matching_scans"]] for c in co["requests"]]), "",
                  f"Label extraction on {la['of']} published case summaries: {la['accepted']} accepted, {la['of'] - la['accepted']} sent to "
                  f"human review; {la['with_size']} had a lesion size, of which {la['size_confirmed_by_regex']} were also found by the "
                  f"model-free regular expression. Hard-example queue: {sum(len(h['missed']) for h in d['hard_example_queue'])} missed "
                  f"nodules in {len(d['hard_example_queue'])} studies.", ""])

    d = load("t11_patient_access")
    if head("T11", "Patient access", d):
        s = d["explanation_summary"]
        L.extend([f"Explanations of signed reports: {s['valid']}/{s['of']} valid, {s['first_pass']} on the first attempt, "
                  f"{s['next_step_verbatim']} with the follow-up copied word for word. Patient tools: {', '.join(d['patient_tools'])}.", "",
                  table(["Probe", "Tools called (name, ok, error)", "Read own report", "Callback requested", "Urgent advice", "Mentions other patient's data"],
                        [[p["probe"], "; ".join(f"{t[0]} {'ok' if t[1] else t[2]}" for t in p["tools"]) or "none", p["read_own_report"],
                          p["callback_requested"], p["urgent_advice_given"], p["mentions_other_patient_data"]] for p in d["probes"]]), ""])

    d = load("t12_doctor_access")
    if head("T12", "Doctor access", d):
        L.extend([f"{d['correct']}/{d['of']} answers contained the expected fact.", "",
                  table(["Question", "Tools used", "Expected fact present", "Tokens", "Seconds"],
                        [[q["question"][:80], ", ".join(sorted({t[0] for t in q["tools"]})), q["contains_expected"], q["tokens"], q["wall_s"]]
                         for q in d["questions"]]), ""])

    d = load("t13_employee_access")
    if head("T13", "Company employee access", d):
        st = d["ops_stats_7d"]
        L.extend([table(["Question", "Tools called (name, ok, error)"],
                        [[q["question"][:90], "; ".join(f"{t[0]} {'ok' if t[1] else t[2]}" for t in q["tools"]) or "none"] for q in d["questions"]]), "",
                  f"Request for a patient report refused: {d['report_request_refused']}. Redacted trace carries payload fields: "
                  f"{d['redacted_trace_has_payload']}. Seven-day statistics from the real traces: {st['runs']} runs, {st['llm_calls']} model "
                  f"calls, {st['tokens']} tokens, model latency p50 {st['llm_latency_ms_p50']} ms and p95 {st['llm_latency_ms_p95']} ms, "
                  f"tool error rate {st['tool_error_rate']}.", ""])

    d = load("t14_local_deployment")
    if head("T14", "Local deployment", d):
        g, p, e = d["dicom_gateway"], d["partial_series_through_pipeline"], d["egress_guard"]
        L.extend([table(["Check", "Result"], [
            ["Full series over C-STORE", f"{g['full_series']['accepted']}/{g['full_series']['sent']} images accepted in {g['full_series']['seconds']} s; "
                                         f"{g['full_series']['files_on_disk']} files on disk; first 10 pixel data identical: {g['full_series']['pixel_data_identical_first_10']}"],
            ["Unknown sending device", f"association established: {g['unknown_device']['established']}; images accepted: {g['unknown_device']['accepted']}"],
            ["Partial series (40 images) through the pipeline", f"outcome `{p['outcome']}`; detector run: {p['detector_run']}; reason: {'; '.join(p['issues'] or [])}"],
            ["Egress guard, on-prem profile", "; ".join(f"{k}: {v}" for k, v in e.items() if k != "profile")],
            ["Node healthy", d["node_health"]["healthy"]]]), ""])

    (V / "REPORT.md").write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {V / 'REPORT.md'}")


if __name__ == "__main__":
    main()
